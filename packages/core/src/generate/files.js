import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { writeFileAtomic } from '../shared/fs.js';
import { ERRORS } from '../shared/errors.js';
import { findBot } from '../shared/bots.js';
import { routeToTwinUrlPath } from '../shared/routes.js';
import { AEO_SPEC_VERSION } from '../shared/version.js';

/** @import { AiBot } from '../shared/bots.js' */

/**
 * Defined in `api-types.js` with every other shape the dashboard reads, and re-exported here.
 *
 * @typedef {import('../shared/api-types.js').SiteFileName} SiteFileName
 * @typedef {import('../shared/api-types.js').SiteFileStatus} SiteFileStatus
 * @typedef {import('../shared/api-types.js').SiteFileResult} SiteFileResult
 */

/**
 * robots.txt, llms.txt and sitemap.xml (§6).
 *
 * `generate` is the sole owner of all three. `prod` reads them and reports on them at boot, and
 * never writes them - which is why an install that only has opengeo-prod can tell you the files are
 * missing but cannot quietly create them behind your back.
 *
 * All three come from the one crawl that already produced the markdown twins.
 *
 * §17's "what if the file already exists" question is answered the conservative way: never
 * overwrite. A hand-written robots.txt usually encodes intent - a staging disallow, a crawl-delay,
 * a rule for one misbehaving bot - and blowing that away to add a sitemap line is a bad trade.
 * Unless the existing file carries OpenGEO's own marker (meaning we wrote it), the new version goes
 * to `<name>.opengeo-proposed` and the user gets told to diff it.
 */

export const GENERATED_MARKER = 'Generated by OpenGEO';
export const PROPOSED_SUFFIX = '.opengeo-proposed';

/**
 * The marker as OpenGEO writes it: at the start of a comment line, followed by the spec version.
 * A file is ours only when it has that line. A user's file that merely mentions the phrase, in a
 * note or a quote, is not, and gets a proposal beside it like any other hand-written file.
 */
const MARKER_LINE = new RegExp(`^(?:# |<!-- )${GENERATED_MARKER} \\(`, 'm');

/** RFC 9309's product token, plus digits and dots, which real crawler tokens use. */
const ROBOTS_TOKEN = /^[A-Za-z0-9_.-]+$/;

/**
 * @typedef {object} SitePage
 * @property {string} route
 * @property {string} url Absolute URL of the human page.
 * @property {string} title
 * @property {string} [description]
 * @property {number} [tokens]
 * @property {string} [lastUpdated]
 */

/**
 * @typedef {object} SiteFilesOptions
 * @property {string} site
 * @property {string} publicDir
 * @property {SitePage[]} pages
 * @property {readonly string[]} [blocked] Bot names from config.bots.blocked. Empty means block
 *   nobody, which is the default (§7).
 * @property {readonly AiBot[]} [bots] The catalogue those names resolve against, so a project's own
 *   crawler gets its declared robots.txt token rather than being written out verbatim. Defaults to
 *   the shipped list.
 * @property {string} [siteName] Site name for the llms.txt H1. Defaults to the hostname.
 * @property {string} [siteDescription] One-line summary for the llms.txt blockquote.
 * @property {boolean} [force]
 * @property {readonly SiteFileName[]} [only] Skip one or more files entirely.
 */

/**
 * @param {SiteFilesOptions} options
 * @returns {SiteFileResult[]}
 */
export function writeSiteFiles(options) {
  /** @type {SiteFileName[]} */
  const wanted = options.only ? [...options.only] : ['robots.txt', 'llms.txt', 'sitemap.xml'];
  /** @type {Record<SiteFileName, string>} */
  const contents = {
    'robots.txt': renderRobotsTxt(options),
    'llms.txt': renderLlmsTxt(options),
    'sitemap.xml': renderSitemapXml(options),
  };
  return wanted.map((name) => writeGuarded(join(options.publicDir, name), name, contents[name], options.force ?? false));
}

/**
 * Write unless it would clobber someone's own file.
 *
 * The marker check is a line match rather than a hash, so a user can hand-edit a file OpenGEO
 * wrote (add a Crawl-delay, say) and still have it recognised as ours on the next run. Deleting the
 * marker line is the way to say "hands off from now on".
 *
 * @param {string} path
 * @param {SiteFileName} name
 * @param {string} contents
 * @param {boolean} force
 * @returns {SiteFileResult}
 */
export function writeGuarded(path, name, contents, force) {
  try {
    const existing = existsSync(path) ? readFileSync(path, 'utf8') : undefined;
    const owned = existing === undefined || MARKER_LINE.test(existing);

    if (owned && existing !== undefined && stripTimestamps(existing) === stripTimestamps(contents)) {
      return { name, path, status: 'unchanged' };
    }

    const written = writeOrPropose(path, contents, owned, force);
    if (written.proposed) return { name, path: written.path, status: 'proposed', message: ERRORS.wouldOverwrite(name) };
    return { name, path, status: 'written' };
  } catch (error) {
    return {
      name,
      path,
      status: 'failed',
      message: error instanceof Error ? error.message : String(error),
    };
  }
}

/**
 * The one writer for a file OpenGEO might not own: twins and site files alike.
 *
 * What counts as owned differs (a marker line in a site file, OpenGEO frontmatter in a twin), and
 * the caller decides that. What happens next does not: a file that is not ours is left exactly as
 * it is and the new version goes beside it as `<name>.opengeo-proposed`, unless `--force` says
 * otherwise.
 *
 * @param {string} path
 * @param {string} contents
 * @param {boolean} owned
 * @param {boolean} force
 * @returns {{ path: string; proposed: boolean }}
 */
export function writeOrPropose(path, contents, owned, force) {
  if (!owned && !force) {
    const proposedPath = `${path}${PROPOSED_SUFFIX}`;
    writeFileAtomic(proposedPath, contents);
    return { path: proposedPath, proposed: true };
  }
  writeFileAtomic(path, contents);
  return { path, proposed: false };
}

/**
 * The generation timestamp changes on every run, so comparing raw text would report every file as
 * changed forever. Dropping the stamped lines before comparing is what makes "unchanged" honest.
 *
 * @param {string} text
 * @returns {string}
 */
function stripTimestamps(text) {
  return text.replace(/\d{4}-\d{2}-\d{2}T[\d:.]+Z/g, '').trim();
}

/**
 * robots.txt is where lever 2 from §7 - the opt-in block list - actually takes effect. Lever 1
 * (which bots get markdown) lives in prod and never appears here, because who receives which
 * representation is not robots.txt's business.
 *
 * Everything is allowed unless the user explicitly listed it. An unknown bot is never blocked (§16).
 *
 * @param {SiteFilesOptions} options
 * @returns {string}
 */
export function renderRobotsTxt(options) {
  const site = new URL(options.site);
  /** @type {string[]} */
  const lines = [
    `# ${GENERATED_MARKER} (${AEO_SPEC_VERSION}) on ${new Date().toISOString()}`,
    `# Edit freely: OpenGEO only rewrites this file while the line above is present.`,
    ``,
    `User-agent: *`,
    `Allow: /`,
    ``,
  ];

  const tokens = (options.blocked ?? []).map((name) => findBot(name, options.bots)?.robotsToken ?? name).filter(Boolean);
  // A token is written on a line of its own, so one with a newline in it would be directives of its
  // own: "Evil\nUser-agent: *\nDisallow: /" blocks every crawler there is. Anything that is not a
  // plain token is left out and named in a comment, quoted so it stays on one line.
  const blocked = tokens.filter((token) => ROBOTS_TOKEN.test(token));
  for (const token of tokens.filter((token) => !ROBOTS_TOKEN.test(token))) {
    lines.push(`# Skipped ${JSON.stringify(token)}: not a valid robots.txt user-agent token.`);
  }
  if (blocked.length > 0) {
    lines.push(`# Blocked on request. This list is opt-in and empty by default.`);
    for (const token of blocked) {
      lines.push(`User-agent: ${token}`, `Disallow: /`, ``);
    }
  } else {
    lines.push(
      `# No AI crawler is blocked. OpenGEO never adds a block you didn't ask for -`,
      `# add names to bots.blocked in opengeo.config.json to change that.`,
      ``,
    );
  }

  lines.push(`Sitemap: ${new URL('/sitemap.xml', site).toString()}`);
  lines.push(``);
  return lines.join('\n');
}

/**
 * llms.txt, in the shape llmstxt.org describes: an H1, a blockquote summary, then link lists.
 *
 * Each entry points at the markdown twin rather than the HTML page, since the whole point is to
 * hand an agent the cheap, clean representation.
 *
 * @param {SiteFilesOptions} options
 * @returns {string}
 */
export function renderLlmsTxt(options) {
  const site = new URL(options.site);
  const name = options.siteName ?? site.hostname;
  const pages = [...options.pages].sort(byRoute);

  /** @type {string[]} */
  const lines = [`# ${name}`, ``];
  if (options.siteDescription) lines.push(`> ${options.siteDescription}`, ``);
  lines.push(
    `Every link below is a Markdown version of the corresponding page, generated from the page`,
    `itself. The same content is available at the page's own URL with \`Accept: text/markdown\`.`,
    ``,
    `## Pages`,
    ``,
  );

  for (const page of pages) {
    const twin = new URL(routeToTwinUrlPath(page.route), site).toString();
    const detail = page.description ? `: ${collapse(page.description)}` : '';
    lines.push(`- [${escapeBrackets(page.title)}](${twin})${detail}`);
  }

  lines.push(``, `<!-- ${GENERATED_MARKER} (${AEO_SPEC_VERSION}) on ${new Date().toISOString()} -->`, ``);
  return lines.join('\n');
}

/**
 * A real `<urlset>`, listing the HTML pages only.
 *
 * The twins are deliberately absent: they carry `X-Robots-Tag: noindex` (§7), so advertising them
 * to a classic search crawler would be asking for the same content to be indexed twice under two
 * URLs, which is exactly the duplicate-content problem the rewrite-not-redirect design avoids.
 *
 * @param {SiteFilesOptions} options
 * @returns {string}
 */
export function renderSitemapXml(options) {
  const pages = [...options.pages].sort(byRoute);
  const entries = pages.map((page) => {
    const lastmod = page.lastUpdated ? `\n    <lastmod>${escapeXml(page.lastUpdated)}</lastmod>` : '';
    return `  <url>\n    <loc>${escapeXml(page.url)}</loc>${lastmod}\n  </url>`;
  });

  return [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<!-- ${GENERATED_MARKER} (${AEO_SPEC_VERSION}) on ${new Date().toISOString()} -->`,
    `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">`,
    ...entries,
    `</urlset>`,
    ``,
  ].join('\n');
}

/**
 * @param {SitePage} a
 * @param {SitePage} b
 * @returns {number}
 */
function byRoute(a, b) {
  if (a.route === '/') return -1;
  if (b.route === '/') return 1;
  // Code-unit order, not localeCompare: collation depends on the machine's ICU data and locale, and
  // these files are committed, so the order must not change between two people's laptops.
  return a.route < b.route ? -1 : a.route > b.route ? 1 : 0;
}

/**
 * @param {string} text
 * @returns {string}
 */
function collapse(text) {
  return text.replace(/\s+/g, ' ').trim();
}

/**
 * @param {string} text
 * @returns {string}
 */
function escapeBrackets(text) {
  return collapse(text).replace(/\[/g, '\\[').replace(/\]/g, '\\]');
}

/**
 * @param {string} text
 * @returns {string}
 */
function escapeXml(text) {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}
