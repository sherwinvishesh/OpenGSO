import { existsSync, readFileSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { CHECKS } from '../src/test/checks.js';
import { SSR_MIN_WORDS, TWIN_FULL_RATIO } from '../src/test/runner.js';
import { AI_BOTS } from '../src/shared/bots.js';
import { defaultConfig } from '../src/shared/config.js';
import { contentHash } from '../src/shared/hash.js';
import { countWords } from '../src/shared/tokens.js';
import { extractPage } from '../src/generate/extract.js';
import { parseFrontmatter } from '../src/generate/frontmatter.js';

/**
 * The project site in website/ is published by GitHub Pages and is itself generated by OpenGSO, so
 * it is held to what OpenGSO asks of every site: twins that match their pages, files that list
 * exactly the pages there are, and links that land. Every number it states is checked against the
 * code, the same way docs.test.js holds docs/.
 */

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const site = join(repoRoot, 'website');
const ORIGIN = 'https://sherwinvishesh.github.io/OpenGSO/';
const BASE_PATH = '/OpenGSO/';
const REGENERATE = 'run `opengso generate website --origin https://sherwinvishesh.github.io/OpenGSO` from a copy of the repo and copy the twins, llms.txt and sitemap.xml back';

/** Every content page, with the route it is published at and the twin generate writes for it. */
const PAGES = [
  { file: 'index.html', route: '', twin: 'index.md' },
  { file: 'docs/index.html', route: 'docs/', twin: 'docs.md' },
  { file: 'privacy/index.html', route: 'privacy/', twin: 'privacy.md' },
];
const HTML_FILES = [...PAGES.map((page) => page.file), '404.html'];

/**
 * @param {string} relative
 * @returns {string}
 */
const read = (relative) => readFileSync(join(site, relative), 'utf8');

/**
 * @param {string} html
 * @param {RegExp} pattern One capture group.
 * @returns {string[]}
 */
const all = (html, pattern) => [...html.matchAll(pattern)].map((match) => match[1] ?? '');

/**
 * @param {string} text
 * @returns {string}
 */
const decode = (text) => text.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&amp;/g, '&');

/**
 * The file a URL path on the published site is served from, or undefined for one outside it.
 *
 * @param {string} path An absolute path on the host, without query or fragment.
 * @returns {string | undefined}
 */
function fileFor(path) {
  if (!path.startsWith(BASE_PATH)) return undefined;
  const inside = decodeURIComponent(path.slice(BASE_PATH.length));
  return inside === '' || inside.endsWith('/') ? `${inside}index.html` : inside;
}

/**
 * Every link, script, stylesheet, image and social card a page names on this site, resolved
 * against the address the page is published at.
 *
 * @param {string} file
 * @returns {{ raw: string; url: URL }[]}
 */
function localReferences(file) {
  // Markup shown as text, like the HTML in a figure, is escaped and names nothing.
  const html = read(file).replace(/&lt;[\s\S]*?&gt;/g, '');
  const page = PAGES.find((entry) => entry.file === file);
  // 404.html is served at whatever address was missing, so it is resolved from somewhere deep.
  const pageUrl = new URL(page ? page.route : 'some/missing/page', ORIGIN);
  const raws = [...all(html, /\s(?:href|src)="([^"]+)"/g), ...all(html, /\scontent="(https:\/\/sherwinvishesh\.github\.io\/[^"]*)"/g)];
  return raws
    .filter((raw) => !/^(?:mailto|tel|javascript):/.test(raw))
    .map((raw) => ({ raw, url: new URL(decode(raw), pageUrl) }))
    .filter(({ url }) => url.origin === new URL(ORIGIN).origin);
}

describe('website pages', () => {
  for (const page of PAGES) {
    describe(page.file, () => {
      const html = read(page.file);
      const head = html.split('</head>')[0] ?? '';

      it('has the head every page needs', () => {
        expect(html.startsWith('<!doctype html>')).toBe(true);
        expect(html).toContain('<html lang="en">');
        expect(head).toContain('<meta name="viewport" content="width=device-width, initial-scale=1">');
        expect(head).toMatch(/<title>[^<]{8,}<\/title>/);
        expect(all(head, /<meta name="description" content="([^"]*)">/g)[0]?.length ?? 0).toBeGreaterThanOrEqual(50);
        expect(head).toContain(`<link rel="canonical" href="${ORIGIN}${page.route}">`);
        expect(head).toContain(`<link rel="alternate" type="text/markdown" href="${ORIGIN}${page.twin}">`);
        expect(all(head, /<meta name="robots" content="([^"]*)">/g).join(' ')).not.toContain('noindex');
      });

      it('has exactly one h1 and no repeated id', () => {
        expect(all(html, /<h1\b([^>]*)>/g)).toHaveLength(1);
        const ids = all(html, /\sid="([^"]+)"/g);
        expect(ids.filter((id, i) => ids.indexOf(id) !== i), 'repeated ids').toEqual([]);
      });

      it('carries JSON-LD that parses', () => {
        const blocks = all(html, /<script type="application\/ld\+json">([\s\S]*?)<\/script>/g);
        expect(blocks.length).toBeGreaterThan(0);
        for (const block of blocks) expect(() => JSON.parse(block)).not.toThrow();
      });

      it('has its content in the raw HTML (A5)', () => {
        expect(extractPage(html, { url: `${ORIGIN}${page.route}` }).wordCount).toBeGreaterThanOrEqual(SSR_MIN_WORDS);
      });
    });
  }
});

describe('website twins', () => {
  for (const page of PAGES) {
    it(`${page.twin} was generated from the current ${page.file}`, () => {
      expect(existsSync(join(site, page.twin)), `${page.twin} is missing: ${REGENERATE}`).toBe(true);
      const twin = parseFrontmatter(read(page.twin));
      // Generate names a folder's page without its trailing slash; the sitemap uses the canonical.
      expect(String(twin.data.url).replace(/\/?$/, '/')).toBe(`${ORIGIN}${page.route}`);
      const extracted = extractPage(read(page.file), { url: `${ORIGIN}${page.route}` });
      // The same comparison B14 makes against the live page, made before the page is live.
      expect(contentHash(extracted.markdown), `${page.file} changed after ${page.twin} was written: ${REGENERATE}`).toBe(twin.data.source_hash);
      expect(countWords(twin.body)).toBeGreaterThanOrEqual(extracted.wordCount * TWIN_FULL_RATIO);
    });
  }
});

describe('website links', () => {
  for (const file of HTML_FILES) {
    it(`every link in ${file} lands on a file and an id that exist`, () => {
      const broken = [];
      for (const { raw, url } of localReferences(file)) {
        // A bare fragment stays on the page, wherever 404.html happens to be served.
        const target = raw.startsWith('#') ? file : fileFor(url.pathname);
        if (!target || !existsSync(join(site, target)) || statSync(join(site, target)).isDirectory()) {
          broken.push(`${raw} (no file)`);
          continue;
        }
        const fragment = decodeURIComponent(url.hash.slice(1));
        if (fragment && target.endsWith('.html') && !read(target).includes(` id="${fragment}"`)) broken.push(`${raw} (no #${fragment})`);
      }
      expect(broken).toEqual([]);
    });
  }

  it('404.html names every page on this site by an absolute path', () => {
    // GitHub Pages serves it at the missing address, so a relative link would resolve from there.
    const relative = all(read('404.html'), /\s(?:href|src)="([^"]+)"/g).filter((raw) => !/^(?:https?:|\/|#|mailto:)/.test(raw));
    expect(relative).toEqual([]);
  });
});

describe('website site files', () => {
  it('sitemap.xml lists exactly the content pages', () => {
    const locs = all(read('sitemap.xml'), /<loc>([^<]+)<\/loc>/g).sort();
    expect(locs).toEqual(PAGES.map((page) => `${ORIGIN}${page.route}`).sort());
  });

  it('llms.txt has a title and a summary, and links every twin and nothing else', () => {
    const llms = read('llms.txt');
    expect(llms).toMatch(/^# \S/);
    expect(llms).toMatch(/^> \S/m);
    const links = all(llms, /\]\((https:[^)]+)\)/g).sort();
    expect(links).toEqual(PAGES.map((page) => `${ORIGIN}${page.twin}`).sort());
  });

  it('404.html is kept out of search results', () => {
    expect(read('404.html')).toContain('<meta name="robots" content="noindex">');
  });

  it('has .nojekyll, so Pages serves the twins as files rather than building them', () => {
    expect(existsSync(join(site, '.nojekyll'))).toBe(true);
  });

  it('has no robots.txt, which crawlers only read at the root of the host', () => {
    expect(existsSync(join(site, 'robots.txt'))).toBe(false);
  });
});

describe('website facts', () => {
  const index = read('index.html');
  const docs = read('docs/index.html');
  const sources = [...HTML_FILES.map(read), read('assets/site.js')];

  it('the check table lists every check with its title, weight and kind', () => {
    const rows = [
      ...index.matchAll(/<tr( class="is-key")?><td class="id">(\w+)<\/td><td>(.*?)<\/td><td class="num">(\d+)<\/td><td><span class="pill (scored|sugg)">/g),
    ].map(([, key, id, title, weight, kind]) => ({ id, title: decode(title ?? ''), weight: Number(weight), scored: kind === 'scored', key: Boolean(key) }));
    expect(rows).toEqual(CHECKS.map((check) => ({ id: check.id, title: check.title, weight: check.weight, scored: check.scored, key: check.scored })));
  });

  it('the docs check table agrees on every weight and kind', () => {
    const rows = [...docs.matchAll(/<tr><td>([AB]\d+)<\/td><td>(\d+)<\/td><td>(scored|suggestion)<\/td>/g)].map(([, id, weight, kind]) => ({
      id,
      weight: Number(weight),
      scored: kind === 'scored',
    }));
    expect(rows).toEqual(CHECKS.map((check) => ({ id: check.id, weight: check.weight, scored: check.scored })));
  });

  it('every count in the guarantees matches the code', () => {
    const prod = JSON.parse(readFileSync(join(repoRoot, 'packages/prod/package.json'), 'utf8'));
    const facts = Object.fromEntries([...index.matchAll(/<b data-fact="([\w-]+)">(\d+)<\/b>/g)].map(([, name, value]) => [name, Number(value)]));
    const routed = defaultConfig().bots.markdownRouting;
    const search = AI_BOTS.filter((bot) => bot.kind === 'search').map((bot) => bot.name);
    expect(facts).toEqual({
      'bots-routed': routed.length,
      'bots-known': AI_BOTS.length,
      'bots-search': search.length,
      'prod-deps': Object.keys(prod.dependencies ?? {}).length,
    });
    // The page says none of the search crawlers is routed.
    expect(routed.filter((name) => search.includes(name))).toEqual([]);
  });

  it('Table 2 adds up, and the rest of the page quotes it', () => {
    /** @param {string | undefined} text */
    const bytes = (text) => Number((text ?? '').replace(/,/g, ''));
    const rows = [
      ...index.matchAll(/<tr( class="is-key")?><td class="id">([^<]+)<\/td><td class="num">([\d,]+)<\/td><td class="num">([\d,]+)<\/td><td class="num">([\d.]+)×<\/td><\/tr>/g),
    ].map(([, total, page, html, md, ratio]) => ({ total: Boolean(total), page, html, md, ratio: Number(ratio) }));
    expect(rows.map((row) => row.page)).toEqual(['/', '/about', '/resume', 'all three']);
    for (const row of rows) expect(row.ratio, `${row.page} ratio`).toBe(Number((bytes(row.html) / bytes(row.md)).toFixed(1)));
    const pages = rows.filter((row) => !row.total);
    const sum = rows.find((row) => row.total);
    expect(bytes(sum?.html)).toBe(pages.reduce((n, row) => n + bytes(row.html), 0));
    expect(bytes(sum?.md)).toBe(pages.reduce((n, row) => n + bytes(row.md), 0));

    const resume = rows.find((row) => row.page === '/resume');
    const quoted = Object.fromEntries([...index.matchAll(/data-bytes="([\w-]+)">([\d,]+) B</g)].map(([, name, value]) => [name, value]));
    expect(quoted).toEqual({ 'resume-html': resume?.html, 'resume-md': resume?.md });
    expect(index).toContain(`from ${resume?.html} bytes to ${resume?.md}.`);
    expect(index).toContain(`text/html · ${resume?.html} bytes`);
    expect(index).toContain(`text/markdown · ${resume?.md} bytes`);
  });

  it('the FAQ JSON-LD says exactly what the page says', () => {
    const graph = JSON.parse(all(index, /<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)[0] ?? '{}')['@graph'];
    const faq = graph.find((/** @type {{ '@type': string }} */ node) => node['@type'] === 'FAQPage');
    const visible = [...index.matchAll(/<div class="faq-item reveal"><h3>(.*?)<\/h3><p>(.*?)<\/p><\/div>/g)].map(([, question, answer]) => ({
      question: decode(question ?? ''),
      answer: decode((answer ?? '').replace(/<[^>]+>/g, '')),
    }));
    expect(visible.length).toBeGreaterThan(0);
    expect(faq.mainEntity.map((/** @type {{ name: string; acceptedAnswer: { text: string } }} */ item) => ({ question: item.name, answer: item.acceptedAnswer.text }))).toEqual(visible);
  });

  it('names the current version, and no other except the first release', () => {
    const { version } = JSON.parse(readFileSync(join(repoRoot, 'packages/opengso/package.json'), 'utf8'));
    const named = new Set(sources.flatMap((text) => all(text, /(?<![\d.])(0\.\d+\.\d+)(?![\d.])/g)));
    expect(named.has(version)).toBe(true);
    named.delete(version);
    named.delete('0.1.0');
    expect([...named]).toEqual([]);
  });

  it('has no placeholder, old name or em dash left in it', () => {
    for (const text of sources) {
      expect(text).not.toMatch(/FIG\d_MEASURED|TODO|lorem ipsum/i);
      expect(text).not.toMatch(/open ?geo|omni ?geo/i);
      expect(text).not.toContain('—');
    }
  });
});
